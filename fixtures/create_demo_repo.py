"""Create a small, deterministic demo Git repository for BranchVerse.

Usage:
    python fixtures/create_demo_repo.py [DEST_DIR]

Default DEST_DIR is <system temp>/branchverse-demo-repo. The generator refuses to
write inside an existing Git repository, and will only overwrite a directory it
created itself (identified by a marker file). No network access is used.
"""

from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

MARKER = ".branchverse-demo-marker"
ALICE = ("Alice Andersen", "alice@example.com")
BOB = ("Bob Brandt", "bob@example.com")
CAROL = ("Carol Chen", "carol@example.com")


def _git(repo: Path, args: list[str], env_extra: dict[str, str] | None = None) -> str:
    env = {k: v for k, v in os.environ.items() if not k.startswith("GIT_")}
    env.update(GIT_CONFIG_NOSYSTEM="1", GIT_CONFIG_GLOBAL=os.devnull, GIT_TERMINAL_PROMPT="0")
    env.update(env_extra or {})
    result = subprocess.run(
        ["git", "-C", str(repo), "-c", "commit.gpgsign=false", "-c", "core.autocrlf=false",
         "-c", "core.hooksPath=" + os.devnull, *args],
        env=env, capture_output=True, text=True, check=True, shell=False,
    )
    return result.stdout.strip()


def _inside_git_repo(path: Path) -> bool:
    # A previous demo (marker file present) may be regenerated; anything else
    # that is, or sits inside, a Git repository is refused.
    own_demo = (path / MARKER).exists()
    candidates = path.parents if own_demo else [path, *path.parents]
    return any((p / ".git").exists() for p in candidates)


def _prepare(dest: Path) -> None:
    dest = dest.resolve()
    if _inside_git_repo(dest):
        raise SystemExit(f"Refusing to create the demo inside a Git repository: {dest}")
    if dest.exists():
        if (dest / MARKER).exists():
            shutil.rmtree(dest, onexc=_force_remove)
        elif any(dest.iterdir()):
            raise SystemExit(f"{dest} exists and is not a BranchVerse demo directory.")
    dest.mkdir(parents=True, exist_ok=True)


def _force_remove(func, path, _exc) -> None:  # read-only files in .git on Windows
    os.chmod(path, 0o700)
    func(path)


def create_demo_repo(dest: Path) -> Path:
    dest = Path(dest)
    _prepare(dest)
    repo = dest.resolve()
    (repo / MARKER).write_text("generated by fixtures/create_demo_repo.py\n")
    _git(repo, ["init", "-q", "-b", "main"])
    (repo / ".git" / "info").mkdir(exist_ok=True)
    (repo / ".git" / "info" / "exclude").write_text(MARKER + "\n")

    def commit(msg: str, who: tuple[str, str], when: str, files: dict[str, str | None]) -> None:
        for rel, content in files.items():
            target = repo / rel
            if content is None:
                target.unlink()
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content, newline="\n")
        _git(repo, ["add", "-A"])
        stamp = f"{when}T12:00:00+00:00"
        _git(repo, ["commit", "-q", "-m", msg], {
            "GIT_AUTHOR_NAME": who[0], "GIT_AUTHOR_EMAIL": who[1], "GIT_AUTHOR_DATE": stamp,
            "GIT_COMMITTER_NAME": who[0], "GIT_COMMITTER_EMAIL": who[1], "GIT_COMMITTER_DATE": stamp,
        })

    def merge(branch: str, who: tuple[str, str], when: str) -> None:
        stamp = f"{when}T12:00:00+00:00"
        _git(repo, ["merge", "-q", "--no-ff", "-m", f"Merge branch '{branch}'", branch], {
            "GIT_AUTHOR_NAME": who[0], "GIT_AUTHOR_EMAIL": who[1], "GIT_AUTHOR_DATE": stamp,
            "GIT_COMMITTER_NAME": who[0], "GIT_COMMITTER_EMAIL": who[1], "GIT_COMMITTER_DATE": stamp,
        })

    commit("Initial commit", ALICE, "2024-01-08", {
        "README.md": "# Demo\n\nA synthetic project for BranchVerse.\n",
        "src/app.py": "def main():\n    print('hello')\n",
    })
    commit("Add utility helpers", ALICE, "2024-01-10", {
        "src/utils.py": "def clamp(x, lo, hi):\n    return max(lo, min(hi, x))\n",
    })
    commit("Document usage", BOB, "2024-01-15", {
        "docs/guide.md": "# Guide\n\nRun `python src/app.py`.\n",
    })
    _git(repo, ["checkout", "-q", "-b", "feature/login"])
    commit("Add login module", BOB, "2024-01-20", {
        "src/login.py": "def login(user, password):\n    return bool(user and password)\n",
    })
    commit("Add auth helpers", BOB, "2024-01-22", {
        "src/auth.py": "def hash_password(p):\n    return p[::-1]\n",
    })
    _git(repo, ["checkout", "-q", "main"])
    commit("Greet by name", ALICE, "2024-01-25", {
        "src/app.py": "def main(name='world'):\n    print(f'hello {name}')\n",
    })
    _git(repo, ["checkout", "-q", "-b", "feature/search"])
    commit("Add search module", CAROL, "2024-02-01", {
        "src/search.py": "def search(items, q):\n    return [i for i in items if q in i]\n",
    })
    commit("Make search case-insensitive", CAROL, "2024-02-03", {
        "src/search.py": "def search(items, q):\n    return [i for i in items if q.lower() in i.lower()]\n",
    })
    _git(repo, ["checkout", "-q", "feature/login"])
    commit("Use salted hashing", BOB, "2024-02-05", {
        "src/auth.py": "import hashlib\n\ndef hash_password(p, salt='x'):\n    return hashlib.sha256((salt + p).encode()).hexdigest()\n",
    })
    _git(repo, ["checkout", "-q", "main"])
    merge("feature/login", ALICE, "2024-02-08")
    commit("Replace utils with config, drop old guide", BOB, "2024-02-10", {
        "src/utils.py": None,
        "docs/guide.md": None,
        "src/config.py": "DEBUG = False\n",
    })
    merge("feature/search", ALICE, "2024-02-14")
    commit("Update README", ALICE, "2024-02-20", {
        "README.md": "# Demo\n\nA synthetic project for BranchVerse.\n\n## Features\n- login\n- search\n",
    })
    _git(repo, ["tag", "v0.1.0"])
    _git(repo, ["checkout", "-q", "-b", "fix/typo"])
    commit("Fix typo in README", CAROL, "2024-02-22", {
        "README.md": "# Demo\n\nA synthetic project for BranchVerse.\n\n## Features\n- login\n- search\n\nThanks!\n",
    })
    _git(repo, ["checkout", "-q", "main"])
    return repo


if __name__ == "__main__":
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(tempfile.gettempdir()) / "branchverse-demo-repo"
    print(create_demo_repo(target))
